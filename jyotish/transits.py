@dataclass
class BigTransit:
    key: str                         # nodes-2026-12, jupiter-2026-10
    planet: str                      # Ra | Ju
    rashi: int                       # новый знак (для узлов — знак Раху)
    prev_rashi: int
    start: datetime                  # средний узел / вход Юпитера
    start_true: datetime | None      # для узлов — истинный узел
    until: datetime                  # окончательный выход из знака
    returns: list[tuple[datetime, datetime]] = field(default_factory=list)  # ретро-возвраты в прошлый знак

    @property
    def ketu_rashi(self) -> int:
        return (self.rashi + 6) % 12

    @property
    def first_date(self) -> datetime:
        return min(self.start, self.start_true) if self.start_true else self.start


def _transits(planet: str, now: datetime, s: Settings, back_days: int, ahead_days: int) -> list[BigTransit]:
    tz = s.location.zone
    jd0 = to_jd(now - timedelta(days=back_days + 500))   # чтобы ретро-возвраты склеивались с исходным входом
    jd_end = to_jd(now + timedelta(days=ahead_days + 900))  # чтобы найти конец периода
    evs = [e for e in ingresses(jd0, jd_end, (planet,), s)]
    out = []
    i = 0
    while i < len(evs):
        e = evs[i]
        prev = (e.rashi - 1) % 12 if planet != "Ra" else (e.rashi + 1) % 12
        # пропускаем ретроградные возвраты: интересует первое вхождение в новый знак по ходу движения
        forward_next = (e.rashi + 1) % 12 if planet != "Ra" else (e.rashi - 1) % 12
        returns, j, until = [], i + 1, None
        while j < len(evs):
            if evs[j].rashi == prev and j + 1 < len(evs) and evs[j + 1].rashi == e.rashi:
                returns.append((from_jd(evs[j].jd, tz), from_jd(evs[j + 1].jd, tz)))
                j += 2
                continue
            if evs[j].rashi == forward_next:
                until = from_jd(evs[j].jd, tz)
            break
        start = from_jd(e.jd, tz)
        if until and now - timedelta(days=back_days) <= start <= now + timedelta(days=ahead_days) \
                and not (out and out[-1].rashi == e.rashi):
            st_true = None
            if planet == "Ra":
                tn = Settings(s.ayanamsha, True, s.location)
                te = [x for x in ingresses(e.jd - 40, e.jd + 40, ("Ra",), tn) if x.rashi == e.rashi]
                st_true = from_jd(te[0].jd, tz) if te else None
            key = f"{ {'Ra': 'nodes', 'Ju': 'jupiter', 'Sa': 'saturn'}[planet]}-{start:%Y-%m}"
            out.append(BigTransit(key, planet, e.rashi, prev, start, st_true, until, returns))
        i = j if j > i else i + 1
    return out


def big_transits(now: datetime, s: Settings | None = None, back_days: int = 120,
                 ahead_days: int = 90) -> list[BigTransit]:
    """Смена узлов, ингрессии Юпитера и Сатурна, начавшиеся недавно или скоро."""
    s = s or Settings()
    found = [t for p in ("Ra", "Ju", "Sa") for t in _transits(p, now, s, back_days, ahead_days)]
    return sorted(found, key=lambda t: t.first_date)


def house(from_rashi: int, planet_rashi: int) -> int:
    return (planet_rashi - from_rashi) % 12 + 1


def sign_ru(r: int) -> str:
    return RASHI[r]["ru"]


def planet_ru(c: str) -> str:
    return PLANET_RU[c]

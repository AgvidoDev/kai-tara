TERMS_BY_LANG: dict[str, dict[str, Term]] = {}
_COMPILED: dict[str, list[tuple[str, re.Pattern]]] = {}


def terms(lang: str = "ru") -> dict[str, Term]:
    if not TERMS_BY_LANG:
        TERMS_BY_LANG.update(_terms_by_lang())
    return TERMS_BY_LANG.get(lang, TERMS)


def categories(lang: str = "ru") -> dict[str, str]:
    if lang == "en":
        from .glossary_en import CATEGORIES_EN
        return CATEGORIES_EN
    return CATEGORIES


def _compiled(lang: str) -> list[tuple[str, re.Pattern]]:
    if lang not in _COMPILED:
        out = []
        for t in terms(lang).values():
            for p in t.patterns:
                flags = re.IGNORECASE if p.startswith("(?i)") else 0
                out.append((t.key, re.compile(p.removeprefix("(?i)"), flags)))
        _COMPILED[lang] = out
    return _COMPILED[lang]


def matches(text: str, lang: str = "ru") -> list[tuple[int, int, str]]:
    """Непересекающиеся вхождения терминов: (start, end, key); каждый ключ — только первый раз.

    При пересечении выигрывает более длинное совпадение («8-й дом» важнее «дом»)."""
    found = []
    for key, rx in _compiled(lang):
        for m in rx.finditer(text):
            if m.end() > m.start():
                found.append((m.start(), m.end(), key))
    found.sort(key=lambda x: (x[0], -(x[1] - x[0])))
    out, used, last_end = [], set(), -1
    for s, e, k in found:
        if s < last_end or k in used:
            continue
        out.append((s, e, k))
        used.add(k)
        last_end = e
    return out


def find_terms(text: str, lang: str = "ru") -> list[str]:
    return [k for _, _, k in matches(text, lang)]


def by_category(cat: str, lang: str = "ru") -> list[Term]:
    return [t for t in terms(lang).values() if t.category == cat]
